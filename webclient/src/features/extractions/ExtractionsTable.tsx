import { DataTable } from "primereact/datatable";
import React from "react";
import { useExtractions } from "../../contexts/GeneratedExtractionsContext";
import { Column } from "primereact/column";
import { useTranslation } from "react-i18next";
import DeleteButton from "../../components/buttons/DeleteButton";
import { OwnedItemType, useAccess } from "../../contexts/AccessContext";
import DataTablePaginator from "../../components/DataTablePaginator";
import { Extraction } from "../../adapters/ApiExtractions";
import { ActionType } from "../../types/ActionType";
import InternalLinkButton from "../../components/buttons/InternalLinkButton";
import { formatDatetime } from "../../data/factories/DateFactory";

interface ExtractionsTableProps {}

const ExtractionsTable: React.FC<ExtractionsTableProps> & {
    Paginator: React.FC;
} = ({}) => {
    const { t } = useTranslation();
    const { hasPermission, hasOwnerPermission } = useAccess();

    const { extractions, deleteExtraction } = useExtractions();

    const documentsLink = (extraction: Extraction) => {
        return `/documents?extractionId=${extraction.id}`;
    };

    const categoriesLink = (extraction: Extraction) => {
        return `/categories?extractionId=${extraction.id}`;
    };

    return (
        <DataTable value={extractions} scrollable scrollHeight="flex">
            <Column field="id" header={t("id")} />
            <Column field="generated_by" header={t("Generated by")} />
            <Column
                field="generated_at"
                header={t("Generated at")}
                body={(e) => formatDatetime(e.generated_at)}
            />
            <Column field="target_pages" header={t("Target pages count")} />
            <Column field="selected_pages" header={t("Selected pages count")} />
            <Column
                field="documents_count"
                header={t("Documents count")}
                body={(e) => e.document_ids.length}
            />
            <Column
                body={(e) => (
                    <InternalLinkButton
                        label={t("Show in documents")}
                        link={documentsLink(e)}
                    />
                )}
            />
            <Column
                body={(e) => (
                    <InternalLinkButton
                        label={t("Show in categories")}
                        link={categoriesLink(e)}
                    />
                )}
            />
            <Column
                body={(extraction) => (
                    <DeleteButton
                        itemId={extraction.id}
                        disabled={
                            !(
                                hasPermission(ActionType.AdminExtractions) ||
                                hasOwnerPermission(
                                    ActionType.Extract,
                                    OwnedItemType.Extraction,
                                    extraction
                                )
                            )
                        }
                        onDeleteItem={deleteExtraction}
                    />
                )}
            />
        </DataTable>
    );
};

const ExtractionsTablePaginator: React.FC = () => {
    const { numFound, page, setPage, pageSize, setPageSize } = useExtractions();

    return (
        <DataTablePaginator
            numFound={numFound}
            page={page}
            pageSize={pageSize}
            onPageChangeNew={setPage}
            onPageSizeChange={setPageSize}
            numFoundText="extractions.num-found"
        />
    );
};

ExtractionsTable.Paginator = ExtractionsTablePaginator;

export default ExtractionsTable;

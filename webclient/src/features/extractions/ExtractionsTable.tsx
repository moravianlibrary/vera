import { DataTable } from "primereact/datatable";
import React from "react";
import { useExtractions } from "../../contexts/extractions/GeneratedExtractionsContext";
import { Column } from "primereact/column";
import { useTranslation } from "react-i18next";
import { Button } from "primereact/button";
import { Link } from "react-router-dom";
import DeleteButton from "../../components/buttons/DeleteButton";
import { useAccess } from "../../contexts/AccessContext";
import DataTablePaginator from "../../components/DataTablePaginator";
import { Extraction } from "../../adapters/ApiExtractions";
import { ActionType } from "../../types/ActionType";

const ExtractionsTable: React.FC = () => {
    const { t } = useTranslation();
    const { currentUser } = useAccess();

    const {
        extractions,
        numFound,
        page,
        setPage,
        pageSize,
        setPageSize,
        deleteExtraction,
    } = useExtractions();

    const canDeleteExtraction = (extraction: Extraction) => {
        const userActions = currentUser?.actions || [];
        return (
            (extraction.generated_by === currentUser?.username &&
                userActions.includes(ActionType.Extract)) ||
            userActions.includes(ActionType.AdminExtractions)
        );
    };

    const documentsButton = (extraction: Extraction) => {
        return (
            <Link to={`/documents?extractionId=${extraction.id}`}>
                <Button outlined label={t("Show in documents")} />
            </Link>
        );
    };

    const categoriesButton = (extraction: Extraction) => {
        return (
            <Link to={`/categories?extractionId=${extraction.id}`}>
                <Button outlined label={t("Show in categories")} />
            </Link>
        );
    };

    return (
        <div>
            <DataTable
                value={extractions}
                scrollable
                scrollHeight="calc(100vh - 210px)"
            >
                <Column field="id" header={t("id")} />
                <Column field="generated_by" header={t("Generated by")} />
                <Column field="generated_at" header={t("Generated at")} />
                <Column field="target_pages" header={t("Target pages count")} />
                <Column
                    field="selected_pages"
                    header={t("Selected pages count")}
                />
                <Column field="documents_count" header={t("Documents count")} />
                <Column body={documentsButton} />
                <Column body={categoriesButton} />
                <Column
                    body={(extraction) => (
                        <DeleteButton
                            itemId={extraction.id}
                            disabled={!canDeleteExtraction(extraction)}
                            onDeleteItem={deleteExtraction}
                        />
                    )}
                />
            </DataTable>
            <DataTablePaginator
                numFound={numFound}
                page={page}
                onPageChangeNew={setPage}
                pageSize={pageSize}
                onPageSizeChange={setPageSize}
            />
        </div>
    );
};

export default ExtractionsTable;

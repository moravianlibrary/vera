// One digitization list beside the browse list (page-lists.js render): a note on where it
// stands, planned against delivered, what is on it, and its history. A member a gate stopped
// after listing stays on, flagged (flows.md L11); one that could not be digitized carries its
// message, and a cancelled one its reason.
// TODO(rrandiak): the *Counts towards* and *Mix* cards wait for intentions in the mock API
// (plan.md step 6), and the provenance's intention name with them.
// TODO(rrandiak): labels move to i18n.

import { Link } from "react-router";
import type { ListDetail, ListItem } from "@/api/lists";
import type { ViewAction } from "@/components/actions/action-bar";
import { ActionBar } from "@/components/actions/action-bar";
import { categoryLabelOf } from "@/components/classification-fields";
import { DetailCard, DetailRow, Muted, StatTiles } from "@/components/detail-card";
import { visibleNavigation } from "@/components/layout/navigation";
import { HistoryCard, RecordHeading } from "@/components/record-cards";
import { StatusWithFootnote } from "@/components/status-badge";
import { StatusNote } from "@/components/status-note";
import { documentIdentifierOf } from "@/domain/documents";
import type { Session } from "@/domain/entities";
import type { MemberBlocker } from "@/domain/lists";
import { isScanned } from "@/domain/lists";
import { hasPermission } from "@/domain/permissions";
import { iterationStatusOf, statusFootnoteOf } from "@/domain/status";
import { useCategoriesQuery, useUsersQuery } from "@/hooks/use-reference-query";
import { formatCalendarDay, formatDay } from "@/lib/format-date";
import { formatCount } from "@/lib/format-number";
import { plural } from "@/lib/plural";

const blockerTexts = {
  Forbidden: "forbidden by a rule",
  ReviewNeeded: "review needed",
  ValidationDenied: "denied in review",
} as const satisfies Record<MemberBlocker, string>;

interface ListDetailPaneProps {
  detail: ListDetail;
  session: Session;
}

export function ListDetailPane({ detail, session }: ListDetailPaneProps) {
  const { row, members, log } = detail;
  const { list } = row;
  const { data: users = [] } = useUsersQuery();
  const nameOf = (userId: string) => users.find((user) => user.id === userId)?.name ?? userId;
  const documents = visibleNavigation(session).find((entry) => entry.id === "documents");
  const documentHref = (item: ListItem) =>
    documents === undefined
      ? undefined
      : `${documents.path}?id=${encodeURIComponent(item.document.id)}`;
  const average = row.itemCount === 0 ? null : Math.round(row.pages / row.itemCount);
  // A Done list is history: nothing on it or about it changes.
  const actions: ViewAction[] =
    hasPermission(session, "list.edit") && row.state !== "Done"
      ? [
          {
            id: "edit",
            label: "Edit",
            isPrimary: true,
            href: `/lists/${encodeURIComponent(list.id)}/edit`,
          },
        ]
      : [];

  return (
    <article className="@container max-w-5xl">
      <div className="flex flex-wrap items-start justify-between gap-x-4">
        <RecordHeading
          title={list.name}
          identifier={list.id}
          details={[
            `${formatCalendarDay(list.startsOn)} → ${formatCalendarDay(list.endsOn)}`,
            list.generated === null ? null : `generated by ${list.generated.generator}`,
          ]}
        />
        <ActionBar actions={actions} menuLabel="More" className="mb-4" />
      </div>
      <StateNote detail={detail} nameOf={nameOf} />

      <StatTiles
        stats={[
          {
            label: "Pages planned",
            value: formatCount(row.pages),
            foot:
              list.targetPages === null
                ? "no target set"
                : `of ${formatCount(list.targetPages)} it was built towards`,
            meter: list.targetPages === null ? undefined : (row.pages / list.targetPages) * 100,
          },
          {
            label: "Delivered",
            value: formatCount(row.scannedPages),
            foot: `pages digitized · ${row.scannedItemCount} of ${row.itemCount} items`,
            meter: row.pages === 0 ? 0 : (row.scannedPages / row.pages) * 100,
          },
          {
            label: "Items",
            value: row.itemCount,
            foot: average === null ? "empty" : `${formatCount(average)} pp on average`,
          },
        ]}
      />

      <div className="mt-4 grid gap-4">
        <DetailCard title={`On this list — ${members.length}`}>
          {members.length === 0 && <Muted>Nothing yet.</Muted>}
          {members.map((item) => (
            <MemberRow key={item.iteration.id} item={item} href={documentHref(item)} />
          ))}
        </DetailCard>
        <HistoryCard log={log} nameOf={nameOf} isPublic={false} />
      </div>
    </article>
  );
}

function MemberRow({ item, href }: { item: ListItem; href: string | undefined }) {
  const { data: categories = [] } = useCategoriesQuery();
  const { document, iteration } = item;

  return (
    <DetailRow
      aside={
        <span className="flex flex-col items-end gap-1">
          <span className="tabular-nums">
            {item.pages === null ? "—" : `${formatCount(item.pages)} pp`}
          </span>
          <StatusWithFootnote
            status={iterationStatusOf(iteration)}
            footnote={statusFootnoteOf(iteration)}
          />
        </span>
      }
    >
      {href === undefined ? (
        <b className="font-semibold">{document.title}</b>
      ) : (
        <Link to={href} className="font-semibold hover:underline">
          {document.title}
        </Link>
      )}{" "}
      <span className="font-mono text-xs text-muted-foreground">
        {documentIdentifierOf(document)}
      </span>
      <div className="text-muted-foreground">
        {categoryLabelOf(categories, iteration.categoryId)}
      </div>
      <MemberFlag item={item} />
    </DetailRow>
  );
}

// At most one line: a stop someone decided, else a gate that fails, else a late copy.
function MemberFlag({ item }: { item: ListItem }) {
  const { cancellation } = item.iteration;
  if (cancellation?.cause === "NotDigitizable") {
    return (
      <div className="text-tone-red-foreground">
        Could not be digitized: {cancellation.publicText}
      </div>
    );
  }

  if (cancellation !== null) {
    return <div className="text-muted-foreground">Cancelled — {cancellation.publicText}</div>;
  }

  if (item.blocker !== null) {
    return (
      <div>
        <b className="font-semibold text-tone-amber-foreground">
          ⚠ Blocked since listing: {blockerTexts[item.blocker]}
        </b>{" "}
        <Muted>— stays on; take it off if it should not be scanned</Muted>
      </div>
    );
  }

  if (item.lateCopy !== null && !isScanned(item.iteration)) {
    return (
      <div className="text-tone-amber-foreground">
        ⚠ {item.lateCopy.source}: {item.lateCopy.state.toLowerCase()} since{" "}
        {formatDay(item.lateCopy.seenAt)} — a copy appeared after approval
      </div>
    );
  }

  return null;
}

function StateNote({ detail, nameOf }: { detail: ListDetail; nameOf: (userId: string) => string }) {
  const { row, members } = detail;
  const { list } = row;
  const scanned = `${row.scannedItemCount} of ${row.itemCount} digitized so far`;

  if (list.done !== null) {
    const published = members.filter((item) => item.iteration.progress === "Published").length;
    return (
      <StatusNote
        tone="green"
        className="mb-4"
        title={`Done — marked by ${nameOf(list.done.actorId)}, ${formatDay(list.done.at)}`}
      >
        {row.scannedItemCount} digitized, {published} published
        {row.notDigitizableCount > 0 && `, ${row.notDigitizableCount} could not be digitized`}. A
        Done list cannot be deleted.
      </StatusNote>
    );
  }

  if (row.state === "Planned") {
    return (
      <StatusNote
        tone="blue"
        className="mb-4"
        title={`Planned — starts ${formatCalendarDay(list.startsOn)}`}
      >
        {row.itemCount === 0
          ? "Nothing is on it yet."
          : `Its ${plural(row.itemCount, "item reads", "items read")} Planned until then, and In progress that morning — nobody has to act.`}
      </StatusNote>
    );
  }

  if (row.isOverdue) {
    return (
      <StatusNote
        tone="amber"
        className="mb-4"
        title={`Ended ${formatCalendarDay(list.endsOn)} — not marked Done`}
      >
        {scanned}. Marking it Done moves what is on it to Digitized. Mark any that could not be
        digitized first, with a message.
      </StatusNote>
    );
  }

  return (
    <StatusNote
      tone="blue"
      className="mb-4"
      title={`In progress since ${formatCalendarDay(list.startsOn)}`}
    >
      Ends {formatCalendarDay(list.endsOn)}. {scanned}. When the scanning room is through, mark it
      Done.
    </StatusNote>
  );
}

export type Method = "GET" | "POST" | "PUT" | "PATCH" | "DELETE";

export interface EndpointSpec<Params = unknown, Query = unknown, Body = unknown, Value = unknown> {
  method: Method;
  path: string;
  summary: string;
  // The success status when not 200 (or 204 for an entry with no response).
  status?: 201 | 202;
  params?: z.ZodType<Params>;
  query?: z.ZodType<Query>;
  propertyFilters?: boolean;
  body?: z.ZodType<Body>;
  form?: readonly string[];
  // Absent for an endpoint that answers 204 with no body.
  response?: z.ZodType<Value>;
  redirects?: boolean;
  public?: boolean;
  // An endpoint the engine does not serve; the mock serves it until the backend does (DEC-0022).
  engine?: false;
  // The codes of the refusals it may answer (ACT-refusal), besides each status's own.
  codes: readonly string[];
}

// Only for the types: an entry keeps its schemas' types, for the engine's handler.
function spec<Params = undefined, Query = undefined, Body = undefined, Value = undefined>(
  entry: EndpointSpec<Params, Query, Body, Value>,
): EndpointSpec<Params, Query, Body, Value> {
  return entry;
}

function searchQueryOf(keys: readonly string[]) {
  const fixed = new Set(keys);
  return z
    .object(Object.fromEntries(keys.map((key) => [key, z.string().optional()])))
    .catchall(z.string().optional())
    .superRefine((query, context) => {
      for (const key of Object.keys(query)) {
        if (!fixed.has(key) && !key.startsWith("p.")) {
          context.addIssue({ code: "custom", path: [key], message: "Unknown query parameter" });
        }
      }
    });
}

function commaSeparatedEnumParam(schema: z.ZodType): z.ZodString {
  const values = (schema as z.ZodEnum).options.filter(
    (value): value is string => typeof value === "string",
  );
  const alternatives = values
    .map((value) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"))
    .join("|");
  return z.string().regex(new RegExp(`^(?:${alternatives})(?:,(?:${alternatives}))*$`));
}

function queryParamSchema(key: string, enumParams: Record<string, z.ZodType>) {
  const schema = enumParams[key];
  return (schema ? commaSeparatedEnumParam(schema) : z.string()).optional();
}

